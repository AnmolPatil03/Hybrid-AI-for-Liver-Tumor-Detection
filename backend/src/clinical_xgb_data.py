"""
Data loading, splitting and preprocessing for the clinical XGBoost model.

Dataset: data/hcc_xgboost/hcc_synthetic_dataset.xlsx (generated by
src/generate_hcc_xgboost_dataset.py), 5,000 synthetic patients, one row per
patient, so a stratified row-wise split is safe.

To avoid leakage the data is split first, and all imputers/scalers/encoders
are fit on the training split only.
"""

import os
import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import StandardScaler, OneHotEncoder
import joblib

# Tumor markers -> liver function -> demographics -> etiology
FEATURE_COLUMNS = [
    "AFP_ng_mL", "AFP_L3_percent", "DCP_mAU_mL",
    "Albumin_g_dL", "Bilirubin_mg_dL", "Platelet_count_x10e9_L",
    "Age", "Sex",
    "HCV_status", "HBV_status", "Cirrhosis_status",
]
NUMERIC_FEATURES = [
    "AFP_ng_mL", "AFP_L3_percent", "DCP_mAU_mL",
    "Albumin_g_dL", "Bilirubin_mg_dL", "Platelet_count_x10e9_L", "Age",
]
BINARY_FEATURES = ["HCV_status", "HBV_status", "Cirrhosis_status"]
CATEGORICAL_FEATURES = ["Sex"]

TARGET_COLUMN = "HCC"
ID_COLUMN = "Patient_ID"

DEFAULT_DATA_PATH = os.path.join("data", "hcc_xgboost", "hcc_synthetic_dataset.xlsx")
DEFAULT_SPLIT_PATH = os.path.join("outputs", "splits", "clinical_split.csv")
DEFAULT_PREPROCESSOR_PATH = os.path.join("outputs", "models", "clinical_xgb_preprocessor.joblib")

SEED = 42
TRAIN_RATIO = 0.70
VAL_RATIO = 0.15
TEST_RATIO = 0.15


def load_dataset(path=DEFAULT_DATA_PATH):
    """Load the synthetic clinical dataset (patients sheet) as a DataFrame."""
    if not os.path.exists(path):
        raise FileNotFoundError(
            f"Clinical dataset not found at '{path}'. Generate it first with "
            f"`python -m src.generate_hcc_xgboost_dataset`."
        )
    df = pd.read_excel(path, sheet_name="patients")

    missing_cols = set(FEATURE_COLUMNS + [TARGET_COLUMN, ID_COLUMN]) - set(df.columns)
    if missing_cols:
        raise ValueError(f"Dataset is missing expected columns: {sorted(missing_cols)}")

    return df


def split_dataset(df, seed=SEED, train_ratio=TRAIN_RATIO, val_ratio=VAL_RATIO,
                   test_ratio=TEST_RATIO, split_path=DEFAULT_SPLIT_PATH):
    """
    Stratified 70/15/15 split. Patient_ID, split and label are saved to
    `split_path` so the split can be reproduced.

    Returns (train_df, val_df, test_df).
    """
    assert abs((train_ratio + val_ratio + test_ratio) - 1.0) < 1e-9, \
        "Split ratios must sum to 1.0"

    train_df, temp_df = train_test_split(
        df, test_size=(val_ratio + test_ratio),
        stratify=df[TARGET_COLUMN], random_state=seed,
    )
    val_frac_of_temp = val_ratio / (val_ratio + test_ratio)
    val_df, test_df = train_test_split(
        temp_df, test_size=(1.0 - val_frac_of_temp),
        stratify=temp_df[TARGET_COLUMN], random_state=seed,
    )

    ids = [set(train_df[ID_COLUMN]), set(val_df[ID_COLUMN]), set(test_df[ID_COLUMN])]
    assert ids[0].isdisjoint(ids[1]) and ids[0].isdisjoint(ids[2]) and ids[1].isdisjoint(ids[2]), \
        "Patient ID leakage detected across splits."

    os.makedirs(os.path.dirname(split_path), exist_ok=True)
    split_rows = []
    for name, part in (("train", train_df), ("val", val_df), ("test", test_df)):
        for pid, label in zip(part[ID_COLUMN], part[TARGET_COLUMN]):
            split_rows.append({"Patient_ID": pid, "split": name, TARGET_COLUMN: int(label)})
    split_df = pd.DataFrame(split_rows)
    split_df.to_csv(split_path, index=False)

    print(f"[INFO] Split persisted to: {split_path}")
    print(f"[INFO] Train: {len(train_df)}  Val: {len(val_df)}  Test: {len(test_df)}  "
          f"(seed={seed}, ratios={train_ratio}/{val_ratio}/{test_ratio})")

    return train_df, val_df, test_df


def load_split_assignment(split_path=DEFAULT_SPLIT_PATH):
    """Load a previously persisted split file as {Patient_ID: split_name}."""
    if not os.path.exists(split_path):
        raise FileNotFoundError(f"No persisted split found at '{split_path}'. Run split_dataset() first.")
    split_df = pd.read_csv(split_path)
    return dict(zip(split_df[ID_COLUMN], split_df["split"]))


def build_preprocessor():
    """
    Numeric: median impute + standard scale.
    Binary flags: most-frequent impute.
    Sex: most-frequent impute + one-hot (single column).

    Imputation matters at inference time, when OCR may miss a value.
    """
    numeric_pipeline = Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("scaler", StandardScaler()),
    ])
    binary_pipeline = Pipeline([
        ("imputer", SimpleImputer(strategy="most_frequent")),
    ])
    categorical_pipeline = Pipeline([
        ("imputer", SimpleImputer(strategy="most_frequent")),
        ("encoder", OneHotEncoder(drop="if_binary", handle_unknown="ignore")),
    ])

    preprocessor = ColumnTransformer([
        ("numeric", numeric_pipeline, NUMERIC_FEATURES),
        ("binary", binary_pipeline, BINARY_FEATURES),
        ("categorical", categorical_pipeline, CATEGORICAL_FEATURES),
    ])
    return preprocessor


def transform_to_frame(preprocessor, df):
    """
    Transform `df` and keep the column names, so the booster stores readable
    feature names for the decision-tree viewer.
    """
    arr = preprocessor.transform(df[FEATURE_COLUMNS])
    columns = preprocessor.get_feature_names_out()
    return pd.DataFrame(arr, columns=columns, index=df.index)


def fit_preprocessor(preprocessor, train_df):
    """Fit on the training split only."""
    preprocessor.fit(train_df[FEATURE_COLUMNS])
    return preprocessor


def save_preprocessor(preprocessor, path=DEFAULT_PREPROCESSOR_PATH):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    joblib.dump(preprocessor, path)
    print(f"[INFO] Preprocessor saved to: {path}")


def load_preprocessor(path=DEFAULT_PREPROCESSOR_PATH):
    if not os.path.exists(path):
        raise FileNotFoundError(
            f"Preprocessor not found at '{path}'. Train the clinical model first: "
            f"python train_clinical_xgb.py"
        )
    return joblib.load(path)
